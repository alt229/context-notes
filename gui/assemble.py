#!/usr/bin/env python3
"""Build gui/index.html from the sources in gui/src.

The page friends open is one self-contained file: app.py's Content-Security-Policy allows no outside scripts,
styles, fonts or images. The sources are kept apart by atomic design (gui/README.md explains the layers), and this
script puts them back together: one <style> with the CSS layers in order, the body partials in page order, and one
<script> with the JS files in order. gui/src/manifest.json lists the files of each layer.

    python3 gui/assemble.py          writes gui/index.html
    python3 gui/assemble.py --check  exits 1 if gui/index.html is out of date (for tests and CI)

app.py can also call page() to serve the page straight from the sources. Standard library only.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "src"
MANIFEST = SRC / "manifest.json"
PAGE = HERE / "index.html"

HEAD = """<!doctype html>
<!-- Generated by gui/assemble.py from gui/src. Edit the sources, then run: python3 gui/assemble.py -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Context Notes</title>
<style>
"""


def manifest():
    """The lists of source files, in order, from gui/src/manifest.json."""
    return json.loads(MANIFEST.read_text(encoding="utf-8"))


def sources():
    """Every source file the page is built from, in order (so a test or a watcher can look at them)."""
    m = manifest()
    return [SRC / name for key in ("styles", "page", "dialogs", "scripts") for name in m[key]]


def _join(names, marker):
    """Concatenate the named files, each after a one-line comment saying where it came from."""
    parts = []
    for name in names:
        text = (SRC / name).read_text(encoding="utf-8")
        parts.append(marker % name + "\n" + text.rstrip("\n") + "\n")
    return "\n".join(parts)


def page():
    """The whole page as one string of HTML."""
    m = manifest()
    return (HEAD
            + _join(m["styles"], "/* ---- %s ---- */")
            + "</style>\n</head>\n<body>\n<div class=\"wrap\">\n"
            + _join(m["page"], "  <!-- %s -->")
            + "</div>\n\n"
            + _join(m["dialogs"], "<!-- %s -->")
            + "\n<script>\n"
            + _join(m["scripts"], "// ---- %s ----")
            + "</script>\n</body>\n</html>\n")


def main(argv=None):
    args = sys.argv[1:] if argv is None else argv
    built = page()
    if args == ["--check"]:
        current = PAGE.read_text(encoding="utf-8") if PAGE.exists() else ""
        if current != built:
            print(f"{PAGE} is out of date. Run: python3 gui/assemble.py")
            return 1
        print(f"{PAGE} is up to date.")
        return 0
    if args:
        print(__doc__.strip())
        return 2
    PAGE.write_text(built, encoding="utf-8", newline="\n")
    print(f"Wrote {PAGE} ({len(built.splitlines())} lines).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
